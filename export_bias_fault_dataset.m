%% export_tmp36_fault_dataset.m
% Export the Simulink TMP36 fault-injection results to an Excel dataset.
%
% The dataset combines the healthy TMP36 reference from the source CSV
% with the faulty sensor output and measured temperature from Simulink.

%% Fault configuration

faultType = "Bias";
faultID = 1;

% +20 mV sensor-output bias.
faultSeverity_V = 0.020;

% Must match the Timed trigger configured in Fault Analyzer.
faultStart_s = 300;

% Bias remains active until the end of the simulation.
faultDuration_s = Inf;

runID = "TMP36_Bias_20mV_Run001";

%% Validate required workspace variables

if ~exist("tmp36_data", "var")
    error("tmp36_data is not available in the Workspace.");
end

if ~exist("V_faulty_log", "var")
    error("V_faulty_log is not available in the Workspace.");
end

if ~exist("T_measured_log", "var")
    error("T_measured_log is not available in the Workspace.");
end

%% Extract logged Simulink signals

t = double(V_faulty_log.Time(:));
V_sensor_faulty = double(V_faulty_log.Data(:));

t_measured = double(T_measured_log.Time(:));
T_measured = double(T_measured_log.Data(:));

%% Obtain healthy reference from the source dataset

t_source = double(tmp36_data.time_s);

% Interpolate source data to the Simulink fault-signal timestamps.
T_true = interp1( ...
    t_source, ...
    double(tmp36_data.temperature_C), ...
    t, ...
    "linear", ...
    "extrap");

V_sensor_healthy = interp1( ...
    t_source, ...
    double(tmp36_data.tmp36_output_V), ...
    t, ...
    "linear", ...
    "extrap");

%% Align measured temperature with the fault-signal timestamps

T_measured_aligned = interp1( ...
    t_measured, ...
    T_measured, ...
    t, ...
    "linear", ...
    "extrap");

%% Generate sample and fault labels

% A sample is valid when the faulty sensor output is finite.
SampleValid = isfinite(V_sensor_faulty);

% Identify samples occurring during the fault interval.
if isfinite(faultDuration_s)

    FaultActive = ...
        (t >= faultStart_s) & ...
        (t < faultStart_s + faultDuration_s);

else

    FaultActive = t >= faultStart_s;

end

N = numel(t);

FaultType = repmat("Normal", N, 1);
FaultType(FaultActive) = faultType;

FaultID = zeros(N, 1);
FaultID(FaultActive) = faultID;

FaultSeverity = zeros(N, 1);
FaultSeverity(FaultActive) = faultSeverity_V;

Run_ID = repmat(string(runID), N, 1);

%% Create labeled fault dataset

FaultyDataset = table( ...
    (1:N)', ...
    Run_ID, ...
    t, ...
    T_true, ...
    V_sensor_healthy, ...
    V_sensor_faulty, ...
    T_measured_aligned, ...
    SampleValid, ...
    FaultActive, ...
    FaultID, ...
    FaultType, ...
    FaultSeverity, ...
    repmat(faultStart_s, N, 1), ...
    'VariableNames', { ...
    'Sample_ID', ...
    'Run_ID', ...
    'Time_s', ...
    'T_true_C', ...
    'V_sensor_healthy_V', ...
    'V_sensor_faulty_V', ...
    'T_measured_C', ...
    'SampleValid', ...
    'FaultActive', ...
    'Fault_ID', ...
    'FaultType', ...
    'FaultSeverity_V', ...
    'FaultStart_s'});

%% Create results directory

if ~isfolder("results")
    mkdir("results");
end

%% Export dataset to Excel

excelFile = fullfile( ...
    "results", ...
    "TMP36_Bias_20mV_Run001.xlsx");

% Replace the previous output file if it already exists.
if isfile(excelFile)
    delete(excelFile);
end

writetable( ...
    FaultyDataset, ...
    excelFile, ...
    "Sheet", ...
    "Bias_Fault_Data");